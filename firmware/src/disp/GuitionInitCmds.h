//
// Source: the board's esp_lcd BSP, NorthernMan54/JC3248W535EN src/esp_bsp.c `lcd_init_cmds[]`,
// cross-checked byte-for-byte against Arduino_GFX v1.6.0 `axs15231b_init_operations` (the version
// confirmed working on this board, Arduino_GFX#803): all 29 register writes identical except D0
// bytes [10..11] (BSP 42 C2, GFX C2 42) - BSP order kept: swapping to GFX's order was tried on this
// unit against the alternate-row striping and made no difference, so there's no reason to deviate.
// Register values are hardware facts; re-expressed as named arrays because the BSP's C compound
// literals `(uint8_t[]){...}` aren't valid C++. Generated mechanically from the BSP source (then the
